#!/usr/bin/env python3
# ---------------------------------------------------------------------------
# The UI's pixel icons, from their references in docs/prototype/design/icon refs
# to src/ui/pixelIcons.ts (maps for src/ui/PixelIcon.tsx: one character per
# pixel, '.' = clear, colours by key):
#
#   CART   the shop's Buy bookmark, read cell by cell from cart_ref.png
#          (17 x 13 cells on white), its own teal colours
#   COIN   the coin everywhere (Sell bookmark, prices, the HUD): the clover
#          coin of coin_motif_ref.webp (43 x 43 cells on blue), recoloured in
#          coin_palette_ref.png's gold, brown outline and cream shine
#   COIN_SMALL  the same coin redrawn at 16 x 16 for 16-21 px uses (prices,
#          buttons, the HUD), where the 43-cell one would blur
#
#   python3 -I scripts/ui-pixel-icons.py
# ---------------------------------------------------------------------------
import math
import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REFS = os.path.join(ROOT, 'docs/prototype/design/icon refs')
OUT = os.path.join(ROOT, 'src/ui/pixelIcons.ts')


def sample(path, x0, y0, cell, nc, nr):
    img = np.array(Image.open(path).convert('RGB')).astype(int)
    out = []
    for j in range(nr):
        row = []
        for i in range(nc):
            cx, cy = int(x0 + cell * (i + 0.5)), int(y0 + cell * (j + 0.5))
            row.append(tuple(int(v) for v in np.median(img[cy - 5:cy + 6, cx - 5:cx + 6].reshape(-1, 3), axis=0)))
        out.append(row)
    return out


def nearest(c, table):
    return min(table, key=lambda k: sum((a - b) ** 2 for a, b in zip(c, table[k])))


# ---- the cart: its reference's own colours ---------------------------------
CART_REF = {
    '.': (255, 255, 255),
    'r': (251, 36, 52),  # the handle's red tip
    'R': (189, 33, 46),
    'm': (40, 143, 160),  # the frame
    'd': (15, 117, 132),
    'e': (94, 181, 201),  # the basket, light towards the right
    'f': (133, 214, 235),
    'g': (184, 232, 244),
    'w': (0, 97, 122),  # the wheels
    'W': (1, 51, 62),
}
CART_COLORS = {'r': '#fb2434', 'R': '#bd212e', 'm': '#288fa0', 'd': '#0f7584', 'e': '#5eb5c9', 'f': '#85d6eb',
               'g': '#b8e8f4', 'w': '#00617a', 'W': '#01333e'}
cart = [''.join(nearest(c, CART_REF) for c in row)
        for row in sample(os.path.join(REFS, 'cart_ref.png'), 107, 180, 30.65, 17, 13)]

# ---- the coin: the clover coin's cells, in the star coin's gold ------------
COIN_REF = {
    '.': (97, 205, 244),  # the page's blue
    'O': (6, 30, 97),  # the navy outline
    'c': (255, 211, 146),  # the rim's shine
    'R': (253, 167, 37),  # the rim
    'D': (238, 120, 8),  # the rim's shaded bottom
    'S': (253, 88, 34),  # the face's shaded top band
    'F': (253, 139, 0),  # the face
    'L': (65, 190, 68),  # the clover
}
COIN_COLORS = {
    'O': '#5a2a12',  # dark brown outline
    'c': '#fff4c2',  # cream shine
    'W': '#ffffff',  # the sparkle on the shine
    'R': '#fdd23a',  # gold rim
    'D': '#e8960f',  # the rim's shade
    'S': '#d9761a',  # the face's shaded band
    'F': '#f8b616',  # the gold face
    'L': '#ffe57a',  # the clover, light gold
}
N = 43
coin = [''.join(nearest(c, COIN_REF) for c in row)
        for row in sample(os.path.join(REFS, 'coin_motif_ref.webp'), 328, 328, 1344 / N, N, N)]
# the shine's sparkle: the shine's cells nearest the top-left
shine = sorted(((j + i, j, i) for j, row in enumerate(coin) for i, k in enumerate(row) if k == 'c'))[:3]
coin = [list(r) for r in coin]
for _, j, i in shine:
    coin[j][i] = 'W'
coin = [''.join(r) for r in coin]

# ---- the small coin (16 x 16): the same parts, drawn by hand to fit -------
# O outline, c / W shine, R rim, D rim shade, S shaded band, F face, L clover
small = [
    '.....OOOOOO.....',
    '...OOWccccROO...',
    '..OWcRRRRRRRRO..',
    '.OcRROOOOOORRRO.',
    '.OcROFLFFLFORRO.',
    'OcROFSLLLLSFORDO',
    'OcROLLSLLSLLORDO',
    'ORROFLLSSLLFORDO',
    'ORROFLLSSLLFORDO',
    'ORROLLSLLSLLODDO',
    'ORROFSLLLLSFODDO',
    '.ORROFLFFLFODDO.',
    '.ORRDOOOOOODDDO.',
    '..ORDDDDDDDDDO..',
    '...OODDDDDDOO...',
    '.....OOOOOO.....',
]


def ts_map(name, rows):
    return f'export const {name} = [\n' + ''.join(f"  '{r}',\n" for r in rows) + '];\n'


def ts_colors(name, colors):
    return f'export const {name}: Record<string, string> = {{\n' + ''.join(f"  {k}: '{v}',\n" for k, v in colors.items()) + '};\n'


open(OUT, 'w').write(
    '// Generated by scripts/ui-pixel-icons.py from docs/prototype/design/icon refs;\n'
    '// edit the script, not this file. Maps for ./PixelIcon.tsx: one character\n'
    "// per pixel, '.' = clear.\n\n"
    '// the shop\'s Buy bookmark: a shopping cart (cart_ref.png)\n'
    + ts_map('CART', cart) + ts_colors('CART_COLORS', CART_COLORS) + '\n'
    '// the coin: coin_motif_ref.webp\'s clover coin in coin_palette_ref.png\'s gold\n'
    + ts_map('COIN', coin) + '\n'
    '// the same coin at 16 x 16, for the small uses (prices, buttons, the HUD)\n'
    + ts_map('COIN_SMALL', small) + ts_colors('COIN_COLORS', COIN_COLORS))

# previews (not shipped), next to nothing in the repo
prev = os.environ.get('PREVIEW')
if prev:
    hexrgb = lambda h: tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))
    for name, rows, cols, px in (('cart', cart, CART_COLORS, 12), ('coin', coin, COIN_COLORS, 6), ('coin16', small, COIN_COLORS, 16)):
        w = max(map(len, rows))
        im = Image.new('RGB', (w * px, len(rows) * px), (40, 44, 30))
        for j, r in enumerate(rows):
            for i, k in enumerate(r):
                if k in cols:
                    im.paste(hexrgb(cols[k]), (i * px, j * px, (i + 1) * px, (j + 1) * px))
        im.save(os.path.join(prev, name + '.png'))
print('\n'.join(cart), '\n')
print('\n'.join(small))
